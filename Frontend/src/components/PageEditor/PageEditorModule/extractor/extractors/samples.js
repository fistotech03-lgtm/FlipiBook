/**
 * Built-in demo sample generators for instant 1-click testing
 */

import { createDocx } from '@documents/engine/docx.js';
import { paragraph } from '@documents/engine/model.js';
import { createPresentation, savePresentation, addSlide } from '@presentation-lib/pptx/src/api/index.ts';

/**
 * Creates a sample DOCX document Blob
 * @returns {Blob}
 */
export function createSampleDocx() {
  const p1 = paragraph('Quarterly Executive Summary & Strategic Roadmap');
  const p2 = paragraph('This document was automatically generated by the Puter Extractor engine to demonstrate high-fidelity Word (.docx) to PDF conversion.');
  const p3 = paragraph('Key Highlights:');
  const p4 = paragraph('• Seamless client-side parsing without server-side dependencies.');
  const p5 = paragraph('• Original Canvas layout engine preserving margins, line height, and typography.');
  const p6 = paragraph('• Searchable, selectable text layer embedded directly in the resulting PDF.');
  const p7 = paragraph('• Instant PDF export ready for download and distribution.');

  const doc = createDocx([p1, p2, p3, p4, p5, p6, p7]);
  return doc.export();
}

/**
 * Creates a sample PPTX presentation Blob
 * @returns {Promise<Blob>}
 */
export async function createSamplePptx() {
  const pres = createPresentation();
  try {
    addSlide(pres);
  } catch (_) {}

  const bytes = savePresentation(pres);
  return new Blob([bytes], {
    type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  });
}
